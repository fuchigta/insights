// maxScanBufferBytes は bufio.Scanner の最大行バッファ。
// 1 行が数 MB になるケースがあるため大きめに確保する。
const maxScanBufferBytes = 16 * 1024 * 1024

// メタ判定に使う定数。人間の発話ではない本文（system-reminder・スラッシュコマンド・
// ローカルコマンド出力など）をここにまとめて判定する。判定条件を増やす場合もこの 1 箇所を直す。
const (
	metaPrefixSystemReminder     = "<system-reminder>"
	metaPrefixCommandName        = "<command-name>"
	metaPrefixLocalCommandStdout = "<local-command-stdout>"
	metaSubstringLocalCaveat     = "Caveat: The messages below were generated by the user while running local commands"
)

// isMetaText は本文が「人間の発話でないもの」かどうかを判定する。
func isMetaText(text string) bool {
	trimmed := strings.TrimSpace(text)
	switch {
	case strings.HasPrefix(trimmed, metaPrefixSystemReminder):
		return true
	case strings.HasPrefix(trimmed, metaPrefixCommandName):
		return true
	case strings.HasPrefix(trimmed, metaPrefixLocalCommandStdout):
		return true
	case strings.Contains(text, metaSubstringLocalCaveat):
		return true
	default:
		return false
	}
}

// rawRecord は 1 行分の JSONL レコード。type によって使うフィールドが変わる。
type rawRecord struct {
	Type        string      `json:"type"`
	Timestamp   string      `json:"timestamp"`
	Cwd         string      `json:"cwd"`
	GitBranch   string      `json:"gitBranch"`
	Entrypoint  string      `json:"entrypoint"`
	IsSidechain bool        `json:"isSidechain"`
	IsMeta      bool        `json:"isMeta"`
	Effort      string      `json:"effort"`
	AiTitle     string      `json:"aiTitle"`
	Message     *rawMessage `json:"message"`
}

// rawMessage は user/assistant レコードの message フィールド。
type rawMessage struct {
	Content json.RawMessage `json:"content"`
	Model   string          `json:"model"`
	ID      string          `json:"id"`
	Usage   *rawUsage       `json:"usage"`
}

// rawUsage は assistant メッセージのトークン使用量。
type rawUsage struct {
	InputTokens              int               `json:"input_tokens"`
	OutputTokens             int               `json:"output_tokens"`
	OutputTokensDetails      *rawTokenDetails  `json:"output_tokens_details"`
	CacheReadInputTokens     int               `json:"cache_read_input_tokens"`
	CacheCreationInputTokens int               `json:"cache_creation_input_tokens"`
	CacheCreation            *rawCacheCreation `json:"cache_creation"`
	ServiceTier              string            `json:"service_tier"`
}

type rawTokenDetails struct {
	ThinkingTokens int `json:"thinking_tokens"`
}

type rawCacheCreation struct {
	Ephemeral5m int `json:"ephemeral_5m_input_tokens"`
	Ephemeral1h int `json:"ephemeral_1h_input_tokens"`
}

// rawContentBlock は message.content の配列要素（text/thinking/tool_use/tool_result/image など）。
type rawContentBlock struct {
	Type      string          `json:"type"`
	Text      string          `json:"text"`
	Thinking  string          `json:"thinking"`
	ID        string          `json:"id"`
	Name      string          `json:"name"`
	Input     json.RawMessage `json:"input"`
	ToolUseID string          `json:"tool_use_id"`
	Content   json.RawMessage `json:"content"`
	IsError   bool            `json:"is_error"`
}

// Parse は 1 セッションの JSONL を読み、正規化された *model.Session を返す。
// 壊れた行はスキップして読み進め、ファイル全体が壊れているときだけエラーを返す。
func (s *Source) Parse(ref source.Ref) (*model.Session, error) {
	maxLen := s.MaxTextLen
	if maxLen <= 0 {
		maxLen = DefaultMaxTextLen
	}

	f, err := os.Open(ref.Path)
	if err != nil {
		return nil, fmt.Errorf("トランスクリプトを開けませんでした (%s): %w", ref.Path, err)
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 0, 64*1024), maxScanBufferBytes)

	sess := &model.Session{
		Source:         sourceName,
		SessionID:      ref.SessionID,
		TranscriptPath: ref.Path,
	}

	var (
		seq            int
		totalLines     int
		okLines        int
		haveTimestamp  bool
		projectPathSet bool
		firstPromptSet bool
		toolNames      = map[string]string{}
		seenUsageMsgID = map[string]bool{}
	)

	lineNo := 0
	for scanner.Scan() {
		lineNo++
		line := scanner.Bytes()
		if len(bytes.TrimSpace(line)) == 0 {
			continue
		}
		totalLines++

		var rec rawRecord
		if err := json.Unmarshal(line, &rec); err != nil {
			slog.Warn("claude code: トランスクリプト行の解析に失敗しました", "path", ref.Path, "line", lineNo, "error", err)
			continue
		}
		okLines++

		ts, tsOK := parseTimestamp(rec.Timestamp)
		if tsOK {
			if !haveTimestamp || ts.Before(sess.StartedAt) {
				sess.StartedAt = ts
			}
			if ts.After(sess.EndedAt) {
				sess.EndedAt = ts
			}
			haveTimestamp = true
		}

		if rec.Cwd != "" && !projectPathSet {
			sess.ProjectPath = rec.Cwd
			projectPathSet = true
		}
		if rec.GitBranch != "" {
			sess.GitBranch = rec.GitBranch
		}
		if rec.Entrypoint != "" {
			sess.Entrypoint = rec.Entrypoint
		}
		if rec.IsSidechain {
			sess.IsSidechain = true
		}

		switch rec.Type {
		case "ai-title":
			if title := strings.TrimSpace(rec.AiTitle); title != "" {
				sess.Title = title
			}

		case "assistant":
			if rec.Message == nil {
				continue
			}
			msgs, err := convertAssistantRecord(rec, ts, maxLen, toolNames, seenUsageMsgID)
			if err != nil {
				slog.Warn("claude code: assistant レコードの content 解析に失敗しました", "path", ref.Path, "line", lineNo, "error", err)
				continue
			}
			for _, m := range msgs {
				m.Seq = seq
				seq++
				sess.Messages = append(sess.Messages, m)
			}

		case "user":
			if rec.Message == nil {
				continue
			}
			msgs, err := convertUserRecord(rec, ts, maxLen, toolNames)
			if err != nil {
				slog.Warn("claude code: user レコードの content 解析に失敗しました", "path", ref.Path, "line", lineNo, "error", err)
				continue
			}
			for _, m := range msgs {
				m.Seq = seq
				seq++
				sess.Messages = append(sess.Messages, m)
				if !firstPromptSet && m.Role == model.RoleUser && !m.IsMeta {
					sess.FirstPrompt = truncateText(m.Text, 200)
					firstPromptSet = true
				}
			}

		case "attachment", "queue-operation", "last-prompt", "summary":
			// 仕様どおりスキップ（会話本文ではない）。

		default:
			// agent-name / custom-title / bridge-session / mode / permission-mode /
			// system / file-history-* / atis-latch など、正規化対象外の type はスキップする。
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("トランスクリプトの読み取りに失敗しました (%s): %w", ref.Path, err)
	}
	if totalLines > 0 && okLines == 0 {
		return nil, fmt.Errorf("トランスクリプト全体が壊れています (%s): 有効な行がありません", ref.Path)
	}

	if sess.ProjectPath == "" {
		sess.ProjectPath = reconstructProjectPath(filepath.Base(filepath.Dir(ref.Path)))
	}
	sess.ProjectLabel = lastPathElement(sess.ProjectPath)

	// サブエージェント (<slug>/<parent-uuid>/subagents/agent-xxx.jsonl) は
	// レコードに親セッション ID を持つフィールドが無いため、実ファイルパスから復元する。
	// isSidechain の真偽はレコード側の値を優先し、パスは親 ID の特定にだけ使う。
	if parentID := parentSessionIDFromPath(ref.Path); parentID != "" {
		sess.ParentSessionID = parentID
	}

	// サブエージェントには ai-title レコードが無いため、隣接する .meta.json の
	// description を Title として使う（無ければ空のまま）。
	if sess.Title == "" {
		sess.Title = loadAgentMetaDescription(ref.Path)
	}

	sess.ContentHash = contentHash(sess.Messages)

	return sess, nil
}

// convertAssistantRecord は assistant レコード 1 行を 0 件以上の model.Message に変換する。
// Usage は message.id ごとに最初の 1 Message にだけ設定し、同じ応答が複数行に
// 分割されているケース（text/thinking/tool_use が別レコードに分かれる）でも重複計上しない。
func convertAssistantRecord(rec rawRecord, ts time.Time, maxLen int, toolNames map[string]string, seenUsageMsgID map[string]bool) ([]model.Message, error) {
	m := rec.Message
	str, isString, blocks, err := parseContent(m.Content)
	if err != nil {
		return nil, err
	}
	if isString {
		blocks = []rawContentBlock{{Type: "text", Text: str}}
	}

	firstTimeForUsage := true
	if m.ID != "" {
		if seenUsageMsgID[m.ID] {
			firstTimeForUsage = false
		} else {
			seenUsageMsgID[m.ID] = true
		}
	}
	usageAssigned := false

	var out []model.Message
	for _, b := range blocks {
		msg := model.Message{
			Timestamp: ts,
			Role:      model.RoleAssistant,
			Model:     m.Model,
			Effort:    rec.Effort,
		}

		switch b.Type {
		case "text":
			msg.Text = b.Text
		case "thinking":
			msg.Text = b.Thinking
			msg.IsMeta = true
		case "tool_use":
			if b.ID != "" && b.Name != "" {
				toolNames[b.ID] = b.Name
			}
			msg.ToolName = b.Name
			text := summarizeInput(b.Input)
			msg.Text = truncateText(text, maxLen)
			msg.Truncated = runeLen(text) > maxLen
		default:
			// 未知のブロック型はスキップ。
			continue
		}

		if !usageAssigned && firstTimeForUsage {
			msg.Usage = convertUsage(m.Usage)
			usageAssigned = true
		}

		out = append(out, msg)
	}
	return out, nil
}

// convertUserRecord は user レコード 1 行を 0 件以上の model.Message に変換する。
// content が文字列ならそのまま 1 Message、配列なら text/tool_result ブロックをそれぞれ Message にする。
func convertUserRecord(rec rawRecord, ts time.Time, maxLen int, toolNames map[string]string) ([]model.Message, error) {
	m := rec.Message
	str, isString, blocks, err := parseContent(m.Content)
	if err != nil {
		return nil, err
	}

	if isString {
		return []model.Message{{
			Timestamp: ts,
			Role:      model.RoleUser,
			Text:      str,
			IsMeta:    rec.IsMeta || isMetaText(str),
		}}, nil
	}

	var out []model.Message
	for _, b := range blocks {
		switch b.Type {
		case "text":
			out = append(out, model.Message{
				Timestamp: ts,
				Role:      model.RoleUser,
				Text:      b.Text,
				IsMeta:    rec.IsMeta || isMetaText(b.Text),
			})
		case "tool_result":
			text := extractResultText(b.Content)
			truncated := runeLen(text) > maxLen
			out = append(out, model.Message{
				Timestamp: ts,
				Role:      model.RoleTool,
				Text:      truncateText(text, maxLen),
				Truncated: truncated,
				ToolName:  toolNames[b.ToolUseID],
				IsError:   b.IsError,
			})
		default:
			// image など未対応のブロック型はスキップ。
		}
	}
	return out, nil
}

// convertUsage は rawUsage を model.Usage に変換する。
// cache_creation が無い場合は cache_creation_input_tokens を 5m 側の値として扱う。
func convertUsage(u *rawUsage) *model.Usage {
	if u == nil {
		return nil
	}
	out := &model.Usage{
		InputTokens:  u.InputTokens,
		OutputTokens: u.OutputTokens,
		CacheRead:    u.CacheReadInputTokens,
		ServiceTier:  u.ServiceTier,
	}
	if u.OutputTokensDetails != nil {
		out.ThinkingTokens = u.OutputTokensDetails.ThinkingTokens
	}
	if u.CacheCreation != nil {
		out.CacheCreation5m = u.CacheCreation.Ephemeral5m
		out.CacheCreation1h = u.CacheCreation.Ephemeral1h
	} else if u.CacheCreationInputTokens > 0 {
		out.CacheCreation5m = u.CacheCreationInputTokens
	}
	return out
}

// parseContent は message.content（文字列 or ブロック配列）を判別してパースする。
func parseContent(raw json.RawMessage) (str string, isString bool, blocks []rawContentBlock, err error) {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return "", false, nil, nil
	}
	if trimmed[0] == '"' {
		if err := json.Unmarshal(raw, &str); err != nil {
			return "", false, nil, fmt.Errorf("content(string) の解析に失敗しました: %w", err)
		}
		return str, true, nil, nil
	}
	if err := json.Unmarshal(raw, &blocks); err != nil {
		return "", false, nil, fmt.Errorf("content(array) の解析に失敗しました: %w", err)
	}
	return "", false, blocks, nil
}

// extractResultText は tool_result ブロックの content（文字列 or ブロック配列）からテキストを取り出す。
func extractResultText(raw json.RawMessage) string {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return ""
	}
	if trimmed[0] == '"' {
		var s string
		if err := json.Unmarshal(raw, &s); err == nil {
			return s
		}
		return string(raw)
	}
	if trimmed[0] == '[' {
		var blocks []rawContentBlock
		if err := json.Unmarshal(raw, &blocks); err == nil {
			var parts []string
			for _, b := range blocks {
				if b.Text != "" {
					parts = append(parts, b.Text)
				} else if b.Type != "" {
					parts = append(parts, fmt.Sprintf("[%s]", b.Type))
				}
			}
			return strings.Join(parts, "\n")
		}
	}
	return string(raw)
}

// summarizeInput は tool_use の input を 1 行の JSON 文字列に整形する。
func summarizeInput(raw json.RawMessage) string {
	if len(bytes.TrimSpace(raw)) == 0 {
		return ""
	}
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return string(raw)
	}
	return buf.String()
}

// parseTimestamp は ISO8601 タイムスタンプ（小数秒あり/なし）をパースする。
func parseTimestamp(s string) (time.Time, bool) {
	if s == "" {
		return time.Time{}, false
	}
	if t, err := time.Parse(time.RFC3339Nano, s); err == nil {
		return t, true
	}
	if t, err := time.Parse(time.RFC3339, s); err == nil {
		return t, true
	}
	return time.Time{}, false
}

// runeLen は文字列のルーン数（マルチバイト文字を 1 文字として数える）。
func runeLen(s string) int {
	return len([]rune(s))
}

// truncateText は s をルーン単位で maxLen 文字に切り詰める。
func truncateText(s string, maxLen int) string {
	r := []rune(s)
	if len(r) <= maxLen {
		return s
	}
	return string(r[:maxLen])
}

// contentHash は正規化後の全メッセージ（Role/Model/ToolName/Text）から SHA-256 を計算する。
// フィールド間・メッセージ間を制御文字で区切り、値の中身が偶然一致しても衝突しないようにする。
func contentHash(messages []model.Message) string {
	h := sha256.New()
	for _, m := range messages {
		fmt.Fprintf(h, "%s\x1f%s\x1f%s\x1f%s\x1e", m.Role, m.Model, m.ToolName, m.Text)
	}
	return hex.EncodeToString(h.Sum(nil))
}
